"""Draft -> external review -> promote workflow for verb banks and vocabulary sets.

Drafts live in content/drafts/{verbs,vocabulary}/ (gitignored). An external proof-reader
(ADR 0003) writes findings for each exported prompt; errors are fixed by the local LLM
(--revise) or the item is dropped. A draft whose review found no errors is marked
reviewed and can be promoted to content/verbs/bank/ or content/vocabulary/sets/."""

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal

from pydantic import ValidationError

from contentkit.banks import check_verb_bank, check_vocab_set
from contentkit.conjugation import TENSE_BY_KEY
from contentkit.models import VerbBank, VerbSentence, VocabSet
from contentkit.reference import Reference
from contentkit.validate import Issue
from contentkit.yamlio import dump_yaml, load_yaml, to_data, write_text_atomic

from .bankgen import BankGenerator
from .external_review import Finding, Review

Kind = Literal["verbs", "vocabulary"]
DRAFTS: dict[Kind, Path] = {"verbs": Path("drafts/verbs"), "vocabulary": Path("drafts/vocabulary")}
LIVE: dict[Kind, Path] = {"verbs": Path("verbs/bank"), "vocabulary": Path("vocabulary/sets")}
SCHEMA: dict[Kind, str] = {"verbs": "verb-bank", "vocabulary": "vocab-set"}
REVIEW_DIR = Path("drafts/review")
PROMPT_VERSION = "1"
Bank = VerbBank | VocabSet


def _model(kind: Kind) -> type[VerbBank] | type[VocabSet]:
    return VerbBank if kind == "verbs" else VocabSet


def read(path: Path, kind: Kind) -> Bank:
    return _model(kind).model_validate(load_yaml(path))


def write(root: Path, kind: Kind, bank: Bank, *, live: bool = False) -> Path:
    folder = root / (LIVE if live else DRAFTS)[kind]
    path = (folder / f"{bank.id}.yaml").resolve()
    if not path.is_relative_to(root.resolve()):
        raise ValueError(f"refusing to write outside the content root: {path}")
    depth = "../" * len((LIVE if live else DRAFTS)[kind].parts)
    header = (
        f"# yaml-language-server: $schema={depth}schemas/{SCHEMA[kind]}.schema.json\n"
        "# Generated by the local LLM, checked against the reference data and proof-read.\n"
    )
    write_text_atomic(path, header + dump_yaml(to_data(bank)))
    return path


def next_version(root: Path, kind: Kind, bank_id: str) -> int:
    live = root / LIVE[kind] / f"{bank_id}.yaml"
    return read(live, kind).content_version + 1 if live.exists() else 1


def drafts(root: Path, kind: Kind) -> dict[str, tuple[Path, Bank]]:
    out: dict[str, tuple[Path, Bank]] = {}
    for path in sorted((root / DRAFTS[kind]).glob("*.yaml")):
        bank = read(path, kind)
        out[bank.id] = (path, bank)
    return out


def check(kind: Kind, bank: Bank, ref: Reference) -> list[Issue]:
    where = f"{LIVE[kind]}/{bank.id}.yaml"
    if isinstance(bank, VerbBank):
        return check_verb_bank(bank, ref, where)
    return check_vocab_set(bank, ref, where)


# --- external review -------------------------------------------------------------------------

VERB_PROMPT = """\
You are proof-reading practice sentences that a smaller model wrote for an English-speaking adult \
learning Québec French. Each sentence will be shown with its verb form blanked out, and the \
learner must type the form, so every sentence must be correct and natural. The verb forms were \
checked against a conjugation table, so focus on everything else:
- grammar of the whole sentence: agreement (including the past participle with être), articles, \
prepositions, elision, accents, word order, and whether the tense makes sense in context \
(e.g. a subjunctive needs a trigger; « hier » does not go with a future);
- the subject matches the person given (il = il/elle/on or a singular noun; ils = plural);
- the English translation is accurate;
- the verb's English gloss and the usage note are accurate;
- Québec usage is the default (déjeuner = breakfast, dîner = lunch, souper = supper). Flag a \
Québec claim (region "qc") only when you are certain it is wrong.
Use item_id "gloss", "note", or "s1", "s2"… for the sentences in order. severity "error" = must \
fix; "suggestion" = could be better. Do not report style preferences as errors.

Verified Québec usage:
{lexicon}

Verb: {infinitive}
Gloss: {gloss}
Note: {note}
Sentences:
{sentences}

Answer with a single JSON object matching this JSON Schema:
{schema}"""

VOCAB_PROMPT = """\
You are proof-reading a vocabulary set that a smaller model wrote for an English-speaking adult \
learning Québec French (CEFR {level}). The learner will make flashcards from it, so errors \
teach mistakes. Check every entry:
- the French word: spelling, accents, part of speech, gender (le/la), irregular plural;
- the English gloss is accurate and natural;
- the example sentence is grammatical and natural, actually uses the word with its intended \
meaning, and suits the level; its translation is accurate;
- the note (often the France equivalent of a Québec word) is accurate;
- region "qc" is only for genuine Québec usage, and formality is right (familiar vs standard);
- the word belongs in the set « {title} ».
Québec usage is the default (déjeuner = breakfast, dîner = lunch, souper = supper; « la fin de \
semaine »). Flag a Québec claim only when you are certain it is wrong.
Use item_id = the entry id (or "set" for the set as a whole). severity "error" = must fix; \
"suggestion" = could be better. Do not report style preferences as errors.

Verified Québec usage:
{lexicon}

Entries (JSON):
{entries}

Answer with a single JSON object matching this JSON Schema:
{schema}"""


def _lexicon(ref: Reference) -> str:
    return "\n".join(f"- {t.term}: {t.meaning} (France: {t.france})" for t in ref.quebec) or "-"


def review_prompt(bank: Bank, ref: Reference) -> str:
    schema = json.dumps(Review.model_json_schema(), indent=1)
    if isinstance(bank, VerbBank):
        lines = [
            f"s{i}. [{TENSE_BY_KEY[s.tense].label}, {s.person}, form « {s.form} », "
            f"region {s.region}] {s.fr} — {s.en}"
            for i, s in enumerate(bank.sentences, 1)
        ]
        return VERB_PROMPT.format(
            lexicon=_lexicon(ref),
            infinitive=bank.infinitive,
            gloss=bank.en,
            note=bank.note or "(none)",
            sentences="\n".join(lines),
            schema=schema,
        )
    entries = [e.model_dump(mode="json", exclude_none=True) for e in bank.entries]
    return VOCAB_PROMPT.format(
        level=bank.level,
        title=bank.title,
        lexicon=_lexicon(ref),
        entries=json.dumps(entries, ensure_ascii=False, indent=1),
        schema=schema,
    )


def _stem(kind: Kind, bank_id: str) -> str:
    return f"{kind}-{bank_id}"


def export_reviews(root: Path, ref: Reference, kinds: tuple[Kind, ...]) -> list[str]:
    folder = root / REVIEW_DIR
    folder.mkdir(parents=True, exist_ok=True)
    written = []
    for kind in kinds:
        for bank_id, (_path, bank) in drafts(root, kind).items():
            if bank.provenance and bank.provenance.reviewed_by:
                continue
            stem = _stem(kind, bank_id)
            (folder / f"{stem}.prompt.txt").write_text(review_prompt(bank, ref), encoding="utf-8")
            written.append(stem)
    return written


@dataclass
class ReviewOutcome:
    stem: str
    errors: int = 0
    suggestions: int = 0
    revised: list[str] = field(default_factory=list)
    dropped: list[str] = field(default_factory=list)
    reviewed: bool = False
    problem: str = ""


def import_reviews(
    root: Path, ref: Reference, reviewer: str, generator: BankGenerator | None
) -> list[ReviewOutcome]:
    """Apply every <kind>-<id>.findings.json. Items with errors are revised by the local LLM
    when a generator is given (and need another review round), otherwise dropped."""
    folder = root / REVIEW_DIR
    outcomes = []
    for path in sorted(folder.glob("*.findings.json")):
        stem = path.name.removesuffix(".findings.json")
        kind_name, _, bank_id = stem.partition("-")
        if kind_name not in DRAFTS:
            continue
        kind: Kind = "verbs" if kind_name == "verbs" else "vocabulary"
        outcome = ReviewOutcome(stem)
        outcomes.append(outcome)
        draft_path = root / DRAFTS[kind] / f"{bank_id}.yaml"
        if not draft_path.exists():
            outcome.problem = "no such draft"
            continue
        try:
            review = Review.model_validate_json(path.read_text(encoding="utf-8"))
        except ValidationError as exc:
            outcome.problem = f"invalid findings: {exc.errors()[0]['msg']}"
            continue
        bank = read(draft_path, kind)
        errors = [f for f in review.issues if f.severity == "error"]
        outcome.errors, outcome.suggestions = len(errors), len(review.issues) - len(errors)
        try:
            if isinstance(bank, VerbBank):
                bank = _apply_verb(bank, errors, generator, outcome)
            else:
                bank = _apply_vocab(bank, errors, generator, outcome)
        except ValidationError as exc:
            outcome.problem = f"too little left after the review: {exc.errors()[0]['msg']}"
            continue
        if not outcome.revised and not outcome.problem:
            assert bank.provenance is not None
            provenance = bank.provenance.model_copy(
                update={"reviewed_by": f"{reviewer} (bank prompt v{PROMPT_VERSION})"}
            )
            bank = bank.model_copy(update={"provenance": provenance})
            outcome.reviewed = True
        write(root, kind, bank)
        for leftover in (path, folder / f"{stem}.prompt.txt"):
            leftover.unlink(missing_ok=True)
    return outcomes


def _apply_verb(
    bank: VerbBank, errors: list[Finding], generator: BankGenerator | None, outcome: ReviewOutcome
) -> VerbBank:
    sentences: list[VerbSentence | None] = list(bank.sentences)
    update: dict[str, object] = {}
    for finding in errors:
        item = finding.item_id
        if item == "note":
            update["note"] = None
            outcome.dropped.append("note")
        elif item == "gloss":
            gloss = (
                generator.revise_gloss(bank, finding.problem, finding.suggested_fix)
                if generator
                else None
            )
            if gloss:
                update["en"] = gloss
                outcome.revised.append("gloss")
            else:
                outcome.problem = f"gloss flagged: {finding.problem}"
        elif item.startswith("s") and item[1:].isdigit() and 0 < int(item[1:]) <= len(sentences):
            index = int(item[1:]) - 1
            revised = (
                generator.revise_sentence(bank, index, finding.problem, finding.suggested_fix)
                if generator
                else None
            )
            if revised is not None:
                sentences[index] = revised
                outcome.revised.append(item)
            else:
                sentences[index] = None
                outcome.dropped.append(item)
    update["sentences"] = [s.model_dump() for s in sentences if s is not None]
    return VerbBank.model_validate({**bank.model_dump(), **update})


def _apply_vocab(
    bank: VocabSet, errors: list[Finding], generator: BankGenerator | None, outcome: ReviewOutcome
) -> VocabSet:
    entries = {e.id: e for e in bank.entries}
    for finding in errors:
        entry = entries.get(finding.item_id)
        if entry is None:
            continue
        revised = (
            generator.revise_entry(bank, entry, finding.problem, finding.suggested_fix)
            if generator
            else None
        )
        if revised is not None:
            entries[entry.id] = revised
            outcome.revised.append(entry.id)
        else:
            del entries[entry.id]
            outcome.dropped.append(entry.id)
    return VocabSet.model_validate(
        {**bank.model_dump(), "entries": [e.model_dump() for e in entries.values()]}
    )


# --- promotion ---------------------------------------------------------------------------------


def promote(
    root: Path, ref: Reference, kind: Kind, ids: list[str] | None = None
) -> tuple[list[str], list[str]]:
    """Move reviewed, error-free drafts into the live content tree. Returns (promoted, skipped)."""
    promoted, skipped = [], []
    for bank_id, (path, bank) in drafts(root, kind).items():
        if ids and bank_id not in ids:
            continue
        if not (bank.provenance and bank.provenance.reviewed_by):
            skipped.append(f"{bank_id}: not reviewed yet")
            continue
        errors = [i for i in check(kind, bank, ref) if i.severity == "error"]
        if errors:
            skipped.append(f"{bank_id}: {errors[0].message}")
            continue
        version = next_version(root, kind, bank_id)
        if bank.content_version < version:
            bank = bank.model_copy(update={"content_version": version})
        write(root, kind, bank, live=True)
        path.unlink()
        promoted.append(f"{bank_id} v{bank.content_version}")
    return promoted, skipped
